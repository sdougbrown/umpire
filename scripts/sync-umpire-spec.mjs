import fs from 'node:fs'
import fsPromises from 'node:fs/promises'
import path from 'node:path'
import crypto from 'node:crypto'
import os from 'node:os'
import childProcess from 'node:child_process'
import { fileURLToPath } from 'node:url'

import { stageDirectoryReplacement } from './lib/replace-directory.mjs'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const PIN_FILE = path.join(ROOT, 'umpire-spec.pin.json')
const TARGET_DIR = path.join(ROOT, 'packages', 'json', 'conformance')
const MARKER = path.join(TARGET_DIR, '.synced-at-version')

// ── helpers ──────────────────────────────────────────────────────────────────

function sha256hex(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex')
}

async function fixtureDigest(dir) {
  const entries = []
  await walk(dir, dir, entries)
  // sort by relative path (byte order)
  entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
  const parts = []
  for (const [rel, hex] of entries) {
    parts.push(Buffer.from(rel, 'utf8'))
    parts.push(Buffer.from([0]))
    parts.push(Buffer.from(hex, 'utf8'))
    parts.push(Buffer.from([0]))
  }
  const combined = Buffer.concat(parts)
  return sha256hex(combined)
}

async function walk(baseDir, dir, entries) {
  const dirents = await fsPromises.readdir(dir, { withFileTypes: true })
  for (const dirent of dirents) {
    if (dirent.name === '.synced-at-version') continue
    const full = path.join(dir, dirent.name)
    const rel = path.relative(baseDir, full)
    if (dirent.isDirectory()) {
      await walk(baseDir, full, entries)
    } else if (dirent.isFile()) {
      const buf = await fsPromises.readFile(full)
      const hex = sha256hex(buf)
      entries.push([rel, hex])
    } else {
      throw new Error(`Unsupported fixture entry: ${rel}`)
    }
  }
}

// ── check mode ───────────────────────────────────────────────────────────────

async function runCheck() {
  // 1. Read pin
  let pin
  try {
    pin = JSON.parse(fs.readFileSync(PIN_FILE, 'utf8'))
  } catch (err) {
    console.error(`ERROR: Cannot read ${PIN_FILE}: ${err.message}`)
    process.exit(1)
  }

  // 2. Read marker
  let marker
  try {
    marker = JSON.parse(fs.readFileSync(MARKER, 'utf8'))
  } catch (err) {
    console.error(
      `ERROR: Marker file not found at ${MARKER}. Regenerate by running the sync script.`,
    )
    process.exit(1)
  }

  // 3. Version + tarball SHA match
  if (marker.version !== pin.version) {
    console.error(
      `ERROR: Marker version "${marker.version}" does not match pinned version "${pin.version}". The marker must be regenerated by running the sync.`,
    )
    process.exit(1)
  }
  if (marker.tarballSha256 !== pin.sha256) {
    console.error(
      `ERROR: Marker tarball SHA-256 does not match pinned SHA-256. The marker must be regenerated by running the sync.`,
    )
    process.exit(1)
  }
  if (marker.fixtureDigest !== pin.fixtureDigest) {
    console.error(
      `ERROR: Marker fixture digest does not match the pinned fixture digest. The marker must be regenerated by running the sync.`,
    )
    process.exit(1)
  }

  // 4. Fixture digest
  const digest = await fixtureDigest(TARGET_DIR)
  if (digest !== pin.fixtureDigest) {
    console.error(
      `ERROR: Fixture digest mismatch. Expected ${pin.fixtureDigest}, got ${digest}. The marker must be regenerated by running the sync.`,
    )
    process.exit(1)
  }

  console.log(`✓ umpire-spec ${pin.version} verified`)
  console.log(`  tarball SHA-256 : ${pin.sha256}`)
  console.log(`  fixture digest  : ${digest}`)
}

// ── sync mode ────────────────────────────────────────────────────────────────

async function runSync() {
  // 1. Resolve archive
  const pin = JSON.parse(fs.readFileSync(PIN_FILE, 'utf8'))
  const versionNoV = pin.version.replace(/^v/, '')
  const DEFAULT_ARCHIVE = `/tmp/umpire-spec-${pin.version}.tar.gz`

  let archive
  const envArchive = process.env.UMPIRE_SPEC_ARCHIVE
  if (envArchive && fs.existsSync(envArchive)) {
    archive = envArchive
  } else if (fs.existsSync(DEFAULT_ARCHIVE)) {
    archive = DEFAULT_ARCHIVE
  } else {
    // Download
    console.log(`Downloading ${pin.url} ...`)
    const resp = await fetch(pin.url)
    if (!resp.ok) {
      console.error(`ERROR: HTTP ${resp.status} downloading ${pin.url}`)
      process.exit(1)
    }
    const tmpDir = os.tmpdir()
    const tmpName = `umpire-spec-${pin.version}-${Date.now()}.tar.gz`
    archive = path.join(tmpDir, tmpName)
    const out = fs.createWriteStream(archive)
    for await (const chunk of resp.body) {
      out.write(chunk)
    }
    out.end()
    await new Promise((res, rej) => {
      out.on('finish', res)
      out.on('error', rej)
    })
  }

  // 2. Verify SHA-256
  const archiveBuf = fs.readFileSync(archive)
  const actualSha = sha256hex(archiveBuf)
  if (actualSha !== pin.sha256) {
    console.error(
      `ERROR: Archive SHA-256 mismatch.\n  expected: ${pin.sha256}\n  actual:   ${actualSha}`,
    )
    process.exit(1)
  }

  // 3. Extract
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'umpire-spec-sync-'))
  const extractCmd = [
    '-xzf',
    archive,
    '-C',
    tmpDir,
    '--strip-components=2',
    `umpire-spec-${versionNoV}/conformance`,
  ]
  childProcess.execFileSync('tar', extractCmd, { stdio: 'inherit' })

  // 4. Verify extracted fixture contents before replacing the vendored tree.
  // --strip-components=2 puts conformance contents at tmpDir root.
  const extractedConformance = tmpDir
  const digest = await fixtureDigest(extractedConformance)
  if (digest !== pin.fixtureDigest) {
    console.error(
      `ERROR: Extracted fixture digest mismatch.\n  expected: ${pin.fixtureDigest}\n  actual:   ${digest}`,
    )
    process.exit(1)
  }

  // 5. Stage a complete tree and marker before replacing the current fixtures.
  const markerContents =
    JSON.stringify(
      {
        version: pin.version,
        tarballSha256: pin.sha256,
        fixtureDigest: digest,
      },
      null,
      2,
    ) + '\n'
  try {
    stageDirectoryReplacement({
      sourceDir: extractedConformance,
      targetDir: TARGET_DIR,
      markerContents,
    })
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true })
  }

  // 6. Summary
  console.log(`✓ Synced umpire-spec ${pin.version}`)
  console.log(`  archive       : ${archive}`)
  console.log(`  target        : ${TARGET_DIR}`)
  console.log(`  fixture digest: ${digest}`)
  console.log(
    `  marker written: ${path.join(TARGET_DIR, '.synced-at-version')}`,
  )
}

// ── main ─────────────────────────────────────────────────────────────────────

const args = process.argv.slice(2)
if (args.includes('--check')) {
  await runCheck()
} else {
  await runSync()
}
