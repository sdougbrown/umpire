import fs from 'node:fs'
import fsPromises from 'node:fs/promises'
import path from 'node:path'
import crypto from 'node:crypto'
import os from 'node:os'
import childProcess from 'node:child_process'
import { fileURLToPath } from 'node:url'

import { stageDirectoryReplacement } from './lib/replace-directory.mjs'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const PIN_FILE = path.join(ROOT, 'umpire-spec.pin.json')

// ── helpers ──────────────────────────────────────────────────────────────────

function sha256hex(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex')
}

async function fixtureDigest(dir) {
  const entries = []
  await walk(dir, dir, entries)
  // sort by relative path (byte order)
  entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
  const parts = []
  for (const [rel, hex] of entries) {
    parts.push(Buffer.from(rel, 'utf8'))
    parts.push(Buffer.from([0]))
    parts.push(Buffer.from(hex, 'utf8'))
    parts.push(Buffer.from([0]))
  }
  const combined = Buffer.concat(parts)
  return sha256hex(combined)
}

async function walk(baseDir, dir, entries) {
  const dirents = await fsPromises.readdir(dir, { withFileTypes: true })
  for (const dirent of dirents) {
    if (dirent.name === '.synced-at-version') continue
    const full = path.join(dir, dirent.name)
    const rel = path.relative(baseDir, full)
    if (dirent.isDirectory()) {
      await walk(baseDir, full, entries)
    } else if (dirent.isFile()) {
      const buf = await fsPromises.readFile(full)
      const hex = sha256hex(buf)
      entries.push([rel, hex])
    } else {
      throw new Error(`Unsupported fixture entry: ${rel}`)
    }
  }
}

// Marker for a target lives inside its vendored dir.
function readPin() {
  return JSON.parse(fs.readFileSync(PIN_FILE, 'utf8'))
}

function markerPath(targetDir) {
  return path.join(ROOT, targetDir, '.synced-at-version')
}

function markerContents(pin, digest) {
  return (
    JSON.stringify(
      {
        version: pin.version,
        tarballSha256: pin.sha256,
        fixtureDigest: digest,
      },
      null,
      2,
    ) + '\n'
  )
}

// ── check mode ───────────────────────────────────────────────────────────────

async function runCheck() {
  let pin
  try {
    pin = readPin()
  } catch (err) {
    console.error(`ERROR: Cannot read ${PIN_FILE}: ${err.message}`)
    process.exit(1)
  }

  let anyError = false
  for (const target of pin.targets) {
    const marker = markerPath(target.dir)
    const dir = path.join(ROOT, target.dir)

    let m
    try {
      m = JSON.parse(fs.readFileSync(marker, 'utf8'))
    } catch (err) {
      console.error(
        `ERROR: Marker file not found at ${marker}. Regenerate by running the sync script.`,
      )
      anyError = true
      continue
    }

    if (m.version !== pin.version) {
      console.error(
        `ERROR: Marker version "${m.version}" does not match pinned version "${pin.version}" in ${target.dir}. The marker must be regenerated by running the sync.`,
      )
      anyError = true
      continue
    }
    if (m.tarballSha256 !== pin.sha256) {
      console.error(
        `ERROR: Marker tarball SHA-256 does not match pinned SHA-256 in ${target.dir}. The marker must be regenerated by running the sync.`,
      )
      anyError = true
      continue
    }

    const digest = await fixtureDigest(dir)
    if (digest !== target.fixtureDigest) {
      console.error(
        `ERROR: Fixture digest mismatch in ${target.dir}. Expected ${target.fixtureDigest}, got ${digest}. The marker must be regenerated by running the sync.`,
      )
      anyError = true
      continue
    }

    console.log(`✓ umpire-spec ${pin.version} verified (${target.dir})`)
  }

  if (anyError) process.exit(1)
  console.log(`  tarball SHA-256 : ${pin.sha256}`)
}

// ── sync mode ────────────────────────────────────────────────────────────────

async function resolveArchive(pin) {
  const DEFAULT_ARCHIVE = `/tmp/umpire-spec-${pin.version}.tar.gz`

  const envArchive = process.env.UMPIRE_SPEC_ARCHIVE
  if (envArchive && fs.existsSync(envArchive)) {
    return envArchive
  }
  if (fs.existsSync(DEFAULT_ARCHIVE)) {
    return DEFAULT_ARCHIVE
  }

  console.log(`Downloading ${pin.url} ...`)
  const resp = await fetch(pin.url)
  if (!resp.ok) {
    console.error(`ERROR: HTTP ${resp.status} downloading ${pin.url}`)
    process.exit(1)
  }
  const tmpName = `umpire-spec-${pin.version}-${Date.now()}.tar.gz`
  const archive = path.join(os.tmpdir(), tmpName)
  const out = fs.createWriteStream(archive)
  for await (const chunk of resp.body) {
    out.write(chunk)
  }
  out.end()
  await new Promise((res, rej) => {
    out.on('finish', res)
    out.on('error', rej)
  })
  return archive
}

/**
 * Resolve a source path from the archive into a standalone directory.
 * A directory source returns as-is; a single file is copied into a temp
 * directory. Returns { sourceDir, cleanup } where `cleanup` removes only the
 * temp dir created for files. Directory sources are cleaned up with the
 * extracted base dir by the caller.
 */
async function materializeSource(baseDir, source) {
  const srcPath = path.join(baseDir, source)
  const stat = fs.statSync(srcPath)
  if (stat.isDirectory()) {
    return { sourceDir: srcPath, cleanup: null }
  }
  const wrapDir = fs.mkdtempSync(path.join(os.tmpdir(), 'umpire-spec-file-'))
  fs.copyFileSync(srcPath, path.join(wrapDir, path.basename(srcPath)))
  return {
    sourceDir: wrapDir,
    cleanup: () => fs.rmSync(wrapDir, { recursive: true, force: true }),
  }
}

async function runSync() {
  const pin = readPin()

  const archive = await resolveArchive(pin)

  // 1. Verify SHA-256
  const archiveBuf = fs.readFileSync(archive)
  const actualSha = sha256hex(archiveBuf)
  if (actualSha !== pin.sha256) {
    console.error(
      `ERROR: Archive SHA-256 mismatch.\n  expected: ${pin.sha256}\n  actual:   ${actualSha}`,
    )
    process.exit(1)
  }

  // 2. Extract the whole archive with the top folder stripped.
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'umpire-spec-sync-'))
  const baseDir = path.join(tmpDir, 'root')
  fs.mkdirSync(baseDir)
  childProcess.execFileSync(
    'tar',
    ['-xzf', archive, '-C', baseDir, '--strip-components=1'],
    {
      stdio: 'inherit',
    },
  )

  try {
    for (const target of pin.targets) {
      const dir = path.join(ROOT, target.dir)

      // 3. Verify extracted content before touching the vendored tree.
      let source
      try {
        source = await materializeSource(baseDir, target.sources[0])
      } catch (err) {
        console.error(
          `ERROR: Could not locate source "${target.sources[0]}" in archive: ${err.message}`,
        )
        process.exit(1)
      }

      const digest = await fixtureDigest(source.sourceDir)
      if (digest !== target.fixtureDigest) {
        console.error(
          `ERROR: Extracted fixture digest mismatch for ${target.dir}.\n  expected: ${target.fixtureDigest}\n  actual:   ${digest}`,
        )
        process.exit(1)
      }

      // 4. Stage a complete tree and marker before replacing current fixtures.
      try {
        stageDirectoryReplacement({
          sourceDir: source.sourceDir,
          targetDir: dir,
          markerContents: markerContents(pin, digest),
        })
      } finally {
        source.cleanup?.()
      }

      console.log(`✓ Synced umpire-spec ${pin.version} -> ${target.dir}`)
      console.log(`  fixture digest: ${digest}`)
      console.log(`  marker written: ${markerPath(target.dir)}`)
    }
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true })
  }

  console.log(`  archive       : ${archive}`)
  console.log(`  tarball SHA-256: ${pin.sha256}`)
}

// ── main ─────────────────────────────────────────────────────────────────────

const args = process.argv.slice(2)
if (args.includes('--check')) {
  await runCheck()
} else {
  await runSync()
}
